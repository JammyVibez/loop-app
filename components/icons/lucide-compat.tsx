function createAnimatedIcon(Icon: React.ComponentType<any>) {
  const AnimatedIcon = React.forwardRef<any, any>((props, ref) => {
    const { color, strokeWidth, absoluteStrokeWidth, ...rest } = props;
    const Component = Icon as any;
    return <Component {...rest} ref={ref} style={{ ...rest.style, ...(color ? { color } : {}) }} />;
  });
  AnimatedIcon.displayName = "AnimatedIcon";
  return AnimatedIcon;
}

