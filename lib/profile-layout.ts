export const PROFILE_PAGE_SECTIONS = ["cover", "profile", "content"] as const
export const PROFILE_SIDEBAR_SECTIONS = [
  "avatar-actions",
  "identity",
  "bio",
  "details",
  "stats",
  "awards",
  "progress",
  "organization",
  "cosmetics",
] as const
export const PROFILE_TAB_SECTIONS = ["about", "loops", "branches", "media", "work", "awards"] as const

export type ProfileLayout = {
  version: 1
  sections: string[]
  sidebar: string[]
  tabs: string[]
  hidden: string[]
}

export const DEFAULT_PROFILE_LAYOUT: ProfileLayout = {
  version: 1,
  sections: [...PROFILE_PAGE_SECTIONS],
  sidebar: [...PROFILE_SIDEBAR_SECTIONS],
  tabs: [...PROFILE_TAB_SECTIONS],
  hidden: [],
}

function orderedUnique(value: unknown, allowed: readonly string[], fallback: readonly string[]) {
  const incoming = Array.isArray(value) ? value : []
  const result = incoming.filter((item): item is string => typeof item === "string" && allowed.includes(item))
  const unique = [...new Set(result)]
  return [...unique, ...fallback.filter((item) => !unique.includes(item))]
}

export function normalizeProfileLayout(value: unknown): ProfileLayout {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return { ...DEFAULT_PROFILE_LAYOUT, sections: [...DEFAULT_PROFILE_LAYOUT.sections], sidebar: [...DEFAULT_PROFILE_LAYOUT.sidebar], tabs: [...DEFAULT_PROFILE_LAYOUT.tabs] }
  }
  const raw = value as Record<string, unknown>
  const hiddenAllowed = [...PROFILE_PAGE_SECTIONS, ...PROFILE_SIDEBAR_SECTIONS]
  const hidden = Array.isArray(raw.hidden)
    ? [...new Set(raw.hidden.filter((item): item is string => typeof item === "string" && hiddenAllowed.includes(item)))]
    : []
  return {
    version: 1,
    sections: orderedUnique(raw.sections, PROFILE_PAGE_SECTIONS, PROFILE_PAGE_SECTIONS),
    sidebar: orderedUnique(raw.sidebar, PROFILE_SIDEBAR_SECTIONS, PROFILE_SIDEBAR_SECTIONS),
    tabs: orderedUnique(raw.tabs, PROFILE_TAB_SECTIONS, PROFILE_TAB_SECTIONS),
    hidden: hidden.filter((item) => item !== "profile" && item !== "content" && item !== "identity" && item !== "avatar-actions"),
  }
}

export function validateProfileLayout(value: unknown): ProfileLayout {
  if (value !== undefined && (!value || typeof value !== "object" || Array.isArray(value))) {
    throw new Error("Profile layout must be an object.")
  }
  return normalizeProfileLayout(value)
}

export function isProfileSectionVisible(layout: ProfileLayout, id: string): boolean {
  return !layout.hidden.includes(id)
}

export function buildProfileLayoutCss(value: unknown): string {
  const layout = normalizeProfileLayout(value)
  const profileIndex = layout.sections.indexOf("profile")
  const contentIndex = layout.sections.indexOf("content")
  const profileBeforeContent = profileIndex <= contentIndex
  const areas = profileBeforeContent ? '"profile content"' : '"content profile"'
  const columns = profileBeforeContent ? "360px minmax(0, 1fr)" : "minmax(0, 1fr) 360px"
  const grid = `.loop-profile-layout-grid { order: ${Math.min(profileIndex, contentIndex)} !important; grid-template-areas: ${areas} !important; grid-template-columns: ${columns} !important; }`
  const page = layout.sections.map((id, index) => {
    const parent = id === "cover" ? ".loop-profile-layout-canvas" : ".loop-profile-layout-grid"
    return `${parent} > [data-profile-section="${id}"] { order: ${index} !important; }`
  })
  const sidebar = layout.sidebar.map((id, index) => {
    const parent = id === "avatar-actions" ? ".loop-profile-sidebar" : ".loop-profile-sidebar-blocks"
    return `${parent} > [data-profile-block="${id}"] { order: ${index} !important; }`
  })
  const tabs = layout.tabs.map((id, index) =>
    `.loop-profile-layout-main [data-profile-tab="${id}"] { order: ${index} !important; }`,
  )
  const mobile = `@media (max-width: 1023px) {
  .loop-profile-layout-grid { display: flex !important; flex-direction: column !important; }
}`
  const hidden = layout.hidden.map((id) =>
    `[data-profile-section="${id}"], [data-profile-block="${id}"] { display: none !important; }`,
  )
  return [
    "/* Loop profile layout — generated by Design */",
    grid,
    ...page,
    ...sidebar,
    ...tabs,
    ...hidden,
    mobile,
  ].join("\n")
}
